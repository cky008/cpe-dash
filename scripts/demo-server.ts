let closing = false;
const shutdown = (): void => {
  if (closing) return;
  closing = true;
  for (const timer of timers) clearInterval(timer);
  void stack.close().finally(() => {
    fs.rmSync(dataDir, { recursive: true, force: true });
    process.exit(0);
  });
};
process.on("SIGINT", shutdown);
process.on("SIGTERM", shutdown);
